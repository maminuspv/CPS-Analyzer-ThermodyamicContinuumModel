def derive_affinity_and_moduli(element: str) -> dict:
    """
    Derives electrostatic nuclear ion affinity A_i (Eq. 1),
    Rose UBER bulk modulus K_der (Eq. 3), and Cauchy-Poisson shear modulus G_der (Eq. 4).
    """
    if element not in PERIODIC_METALS_DB:
        raise KeyError(f"Element '{element}' is not in PERIODIC_METALS_DB.")

    r_pm, z_eff, alpha_rose, nu_0, k_tab, g_tab, v_m, z_val, phi_star, nws = PERIODIC_METALS_DB[element]
    r_m = r_pm * 1e-12

    # Eq. (1): Screened Nuclear Ion Affinity
    a_unscreened_j = (z_eff * (E_CHARGE ** 2)) / (4.0 * np.pi * EPSILON_0 * r_m)
    a_i_j = a_unscreened_j * F_SCREEN
    a_i_ev = a_i_j / E_CHARGE

    # Eq. (3): Rose UBER Bulk Modulus
    v_atom_m3 = (4.0 / 3.0) * np.pi * (r_m ** 3)
    k_der_pa = a_i_j / (9.0 * v_atom_m3 * (alpha_rose ** 2))
    k_der_gpa = k_der_pa * 1e-9

    # Eq. (4): Cauchy-Poisson Shear Modulus
    g_der_gpa = k_der_gpa * (1.5 * (1.0 - 2.0 * nu_0) / (1.0 + nu_0))

    return {
        "element": element,
        "r_pm": r_pm,
        "Z_eff": z_eff,
        "Z_val": z_val,
        "A_i_eV": a_i_ev,
        "K_der_GPa": k_der_gpa,
        "G_der_GPa": g_der_gpa,
        "K_tab_GPa": k_tab,
        "G_tab_GPa": g_tab,
        "V_m_cm3": v_m,
        "phi_star": phi_star,
        "n_ws_13": nws
    }